/// The seeded **items** — the second row of chips. Every one of these hangs off
/// a group by [AppCategory.parentId] and is what a transaction actually points
/// at.
///
/// Ids of the pre-grouping categories (rice, fish, cosmetics, books, hall…)
/// are kept on purpose: an existing ledger keeps its history and simply gains a
/// parent, which is what makes this migration safe.
AppCategory _item(
  String parentId,
  String id,
  String name,
  String nameBn,
  String icon,
  String color,
  int order, {
  bool food = false,
}) => AppCategory(
  id: id,
  name: name,
  nameBn: nameBn,
  icon: icon,
  colorHex: color,
  kind: CategoryKind.expense,
  parentId: parentId,
  sortOrder: order,
  isFood: food,
);

